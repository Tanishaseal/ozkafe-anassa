const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const excluded = new Set(['node_modules','.next','.git','scratch','.agents','.codex']);
const rows=[];
function walk(dir='.') {
  for (const e of fs.readdirSync(dir,{withFileTypes:true})) {
    if(excluded.has(e.name) || e.name.startsWith('.env') || e.name === '.anassa_store.json' || e.name.endsWith('.tsbuildinfo') || e.name === '.DS_Store') continue;
    const p=path.join(dir,e.name); if(e.isDirectory())walk(p); else rows.push({file:p.replaceAll('\\','/'),bytes:fs.statSync(p).size});
  }
}
async function main(){
  walk(); let images=0;
  for (const row of rows) {
    if(/\.svg$/i.test(row.file) && fs.readFileSync(row.file,'utf8').includes('<symbol')) row.check='SVG symbol sprite; no standalone raster dimensions';
    else if(/\.(png|jpe?g|svg)$/i.test(row.file)) { try { const m=await sharp(row.file).metadata(); row.check=`Image decoded: ${m.width} × ${m.height}`;images++; } catch(e) { throw Error(row.file+': '+e.message); } }
    else if(/\.pdf$/i.test(row.file)) row.check='Reference PDF; not executed by the application';
    else if(row.file.startsWith('src/styles/')) row.check='Existing presentation; unchanged';
    else if(row.file.startsWith('src/')) row.check='Application source; covered by TypeScript/build and workflow review';
    else row.check='Configuration, documentation, SQL, or verification tooling';
  }
  const source=fs.readFileSync('src/lib/initialData.ts','utf8');
  const references=[...source.matchAll(/['"](\/images\/[^'"]+)['"]/g)].map(m=>m[1]);
  const missing=[...new Set(references)].filter(p=>!fs.existsSync('public'+p));
  if(missing.length) throw Error('Missing image assets: '+missing.join(', '));
  fs.mkdirSync('docs',{recursive:true});
  fs.writeFileSync('docs/file-inventory.md', '# Project file inventory\n\nGenerated by `node scripts/audit-files.cjs`. Dependency trees, Git internals, build caches, local test output, runtime customer data, and environment secrets are excluded. Images are decoded for integrity; reference PDFs are inventoried, not semantically reviewed.\n\n'+rows.length+' files inventoried; '+images+' images decoded; '+new Set(references).size+' initial menu image references resolved.\n\n| File | Bytes | Check |\n| --- | ---: | --- |\n'+rows.sort((a,b)=>a.file.localeCompare(b.file)).map(r=>`| ${r.file} | ${r.bytes} | ${r.check} |`).join('\n')+'\n');
  console.log(JSON.stringify({files:rows.length,images,menuImageReferences:new Set(references).size,missing:missing.length}));
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
